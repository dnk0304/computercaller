// ── 9. the framing actually disambiguates ──────────────────────────────────
// Without the tags and u8 length prefixes, ("ab","cd") and ("a","bcd") flatten
// to the same context bytes and two different pairings derive the SAME traffic
// keys. This is the bug the whole section exists for.
{
  const base = { peerDeviceId: 'x', pairEpoch: 1 };
  const one = toHex(pairContext({ ...base, userId: 'ab', phoneDeviceId: 'cd' }));
  const two = toHex(pairContext({ ...base, userId: 'a', phoneDeviceId: 'bcd' }));
  check('("ab","cd") and ("a","bcd") produce DIFFERENT context bytes', one !== two, `both are ${one}`);
}
// Tag ranges are disjoint — a SAS transcript can never be replayed as a KDF
// info string. The SAS uses 0x01..0x04; nothing here may.
{
  const tags = [0x11, 0x12, 0x13, 0x14, 0x15, 0x21, 0x22, 0x23, 0x24, 0x25];
  check('no KDF/AEAD tag falls in the SAS range 0x01..0x04', tags.every((t) => t > 0x04));
  check('the KDF and AEAD ranges do not overlap', new Set(tags).size === tags.length);
}

// ── 10. DRIFT GUARD: the spec text and the module must agree ───────────────
// The web/SW lane's equivalent of Android's E2eKdfVectorsTest drift assertion.
// The layout is re-encoded from the constants written in §13.10 of the SPEC —
// parsed out of the markdown, NOT imported from the module — so an edit to
// lib/e2e/kdf.mjs that nobody mirrored into the spec (or the reverse) fails
// here rather than at a pairing.
{
  const specText = readFileSync(SPEC, 'utf8');
  const section = specText.slice(specText.indexOf('### 13.10 Key schedule + AEAD'));
  check('§13.10 exists in the spec', section.length > 0);
  check('§13 names A1 as the amending authority', /AMENDING AUTHORITY/.test(specText));
  check('§13.10 records that A1 calls it §13.9', /A1's own text calls the new section "§13\.9"/.test(specText));

  // Pull the tag bytes out of the spec's own fenced layout blocks. The blocks
  // are located by content, not by position, and `pairEpoch` is read from EACH
  // block separately: it is tagged 0x14 in the pair context and 0x25 in the
  // AAD, and a parser that found only the first would happily "confirm" a spec
  // that had lost the AAD's epoch binding entirely.
  const blocks = section.match(/```[\s\S]*?```/g) || [];
  const ctxBlock = blocks.find((b) => b.includes('pairContext =')) || '';
  const aadBlock = blocks.find((b) => b.includes('AAD =')) || '';
  check('drift guard: §13.10 carries a pairContext block and an AAD block',
    ctxBlock.length > 0 && aadBlock.length > 0);

  const tagIn = (block, pattern) => {
    const m = block.match(new RegExp(`(0x[0-9a-f]{2}) ${pattern}`));
    return m ? m[1] : null;
  };
  const specTag = (block, label) => tagIn(block, `u8\\(len\\) ${label}\\b`);
  const specTags = {
    userId: specTag(ctxBlock, 'userId'),
    phoneDeviceId: specTag(ctxBlock, 'phoneDeviceId'),
    peerDeviceId: specTag(ctxBlock, 'peerDeviceId'),
    pairEpoch: tagIn(ctxBlock, 'be64\\(pairEpoch\\)'),
    recipientKey: tagIn(ctxBlock, 'u8\\(65\\) K_i'),
    frameType: specTag(aadBlock, 'frameType'),
    kid: specTag(aadBlock, 'kid'),
    seq: tagIn(aadBlock, 'be64\\(seq\\)'),
    direction: tagIn(aadBlock, 'u8 direction'),
    aadPairEpoch: tagIn(aadBlock, 'be64\\(pairEpoch\\)'),
  };
  eq('drift guard: the AAD epoch tag is 0x25, not the context\'s 0x14',
    specTags.aadPairEpoch !== specTags.pairEpoch, true);
  for (const [name, v] of Object.entries(specTags)) {
    check(`drift guard: §13.10 states a tag for ${name}`, /^0x[0-9a-f]{2}$/.test(String(v)), String(v));
  }

  // Re-encode pairContext from the SPEC's tags, independently of kdf.mjs.
  const te = new TextEncoder();
  const u8len = (tag, s) => {
    const b = te.encode(s);
    return [tag, b.length, ...b];
  };
  const be64n = (n) => {
    const out = [];
    let v = BigInt(n);
    for (let i = 7; i >= 0; i--) { out[i] = Number(v & 0xffn); v >>= 8n; }
    return out;
  };
  const specContext = Uint8Array.from([
    ...u8len(parseInt(specTags.userId, 16), CTX_INPUT.userId),
    ...u8len(parseInt(specTags.phoneDeviceId, 16), CTX_INPUT.phoneDeviceId),
    ...u8len(parseInt(specTags.peerDeviceId, 16), CTX_INPUT.peerDeviceId),
    parseInt(specTags.pairEpoch, 16), ...be64n(CTX_INPUT.pairEpoch),
  ]);
  eq('drift guard: the spec text re-encodes to the module\'s pairContext bytes',
    toHex(specContext), toHex(CTX));
  eq('drift guard: …and to the frozen vector', toHex(specContext), V.contextBytesHex);

  const specAad = Uint8Array.from([
    ...u8len(parseInt(specTags.frameType, 16), A.frameType),
    ...u8len(parseInt(specTags.kid, 16), A.kid),
    parseInt(specTags.seq, 16), ...be64n(A.seq),
    parseInt(specTags.direction, 16), A.direction,
    parseInt(specTags.aadPairEpoch, 16), ...be64n(A.pairEpoch),
  ]);
  eq('drift guard: the spec text re-encodes to the module\'s AAD bytes', toHex(specAad), toHex(aadA));

  // The reserved-range table is a freeze condition, not decoration.
  for (const range of ['`0x01..0x04`', '`0x11..0x15`', '`0x21..0x25`']) {
    check(`drift guard: §13.10.1 reserves ${range}`, section.includes(range));
  }
  check('drift guard: §13.10 keeps the labels the vectors were derived under',
    section.includes('"cc-e2e-v1/kek"') && section.includes('"cc-e2e-v1/p2c"') && section.includes('"cc-e2e-v1/c2p"'));

  // A2 and A3 land in the spec as §13.10.7 and §13.10.8. Same principle as the
  // tag guard above: an addendum that changed the module but never reached the
  // spec (or the reverse) fails here rather than at a pairing.
  {
    const a2 = section.slice(section.indexOf('#### 13.10.7'), section.indexOf('#### 13.10.8'));
    const a3 = section.slice(section.indexOf('#### 13.10.8'));
    check('drift guard: §13.10.7 exists (A2)', a2.length > 0);
    check('drift guard: §13.10.8 exists (A3)', a3.length > 0);
    check('drift guard: §13.10.7 carries the nonce-prefix labels the vectors were derived under',
      a2.includes(`"${LABEL_NP2C}"`) && a2.includes(`"${LABEL_NC2P}"`));
    check('drift guard: §13.10.7 states L = 4', /L = 4/.test(a2));
    // A2 withdrew A1's rationale, and the withdrawal is the load-bearing part:
    // a spec that kept "defence in depth" would leave rule 3 looking optional.
    check('drift guard: §13.10.7 records that the prefix contributes ZERO uniqueness',
      /zero nonce-uniqueness/i.test(a2));
    check('drift guard: §13.10.7 names rule 3 the SOLE control',
      /SOLE control against nonce reuse/.test(a2));
    check('drift guard: §13.10.7 carries A2 MUST#1 (kid <-> SK strictly 1:1)',
      /strictly 1:1/.test(a2));
    check('drift guard: §13.10.7 carries A2 MUST#2 (never persisted)',
      /never persisted/.test(a2));
    check('drift guard: §13.10.5 rule 2 no longer calls the prefix defence in depth',
      !/defence in depth against a state-restore bug\.\s+Anyone/.test(section));

    // A3: the wire form, the decimal-string rule, and all four MUSTs by name.
    for (const field of ['pairingId', 'phoneDeviceId', 'peerDeviceId', 'pairEpoch']) {
      check(`drift guard: §13.10.8 states ctx.${field}`, a3.includes(field));
    }
    check('drift guard: §13.10.8 pins pairEpoch as a DECIMAL STRING',
      /DECIMAL STRING/.test(a3) && a3.includes('^(0|[1-9][0-9]{0,19})$'));
    eq('drift guard: the spec\'s epoch pattern is the module\'s',
      a3.includes(String(PAIR_EPOCH_WIRE_RE).slice(1, -1)), true);
    check('drift guard: §13.10.8 records that userId stays LOCAL',
      /not transmitted/.test(a3));
    for (const must of ['A3-M1', 'A3-M2', 'A3-M3', 'A3-M4']) {
      check(`drift guard: §13.10.8 carries ${must}`, a3.includes(must));
    }
    check('drift guard: §13.10.8 states the A3-M1 splice as code',
      a3.includes('ctx: block.ctx'));
    check('drift guard: §13.10.8 records that ctx is a precondition of the SAS',
      /SAS computable on the computer side at all/.test(a3));
    check('drift guard: §13.10.8 records persist-before-use for the floor',
      /persist-before-use/.test(a3));
    // Control: these slices must be capable of failing.
    check('drift guard control: a MUST the addenda do NOT define is absent',
      !a3.includes('A3-M9') && !a2.includes('A2 MUST#7'));
  }
  // Control: the parser must be capable of failing. If the section slice were
  // empty or the regexes matched nothing, every assertion above would be
  // vacuously green on a spec that says nothing at all.
  check('drift guard control: a tag the spec does NOT state parses as null',
    specTag('somethingTheSpecNeverMentions') === null);
}

// ── 11. the module is service-worker clean, statically ─────────────────────
{
  // Comments are stripped FIRST. The module's own header explains that it must
  // not touch `window` or `document`; a grep over the raw source matches that
  // prose and fails a module that is in fact clean.
  const src = readFileSync(KDF_MODULE, 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1');
  check('kdf.mjs imports no Node built-in', !/from\s+['"]node:/.test(src));
  check('kdf.mjs touches no DOM global', !/\b(window|document|localStorage)\b/.test(src));
  check('kdf.mjs imports only ./padding.mjs',
    (src.match(/^import .*$/gm) || []).every((l) => l.includes('./padding.mjs')));
  check('the comment-stripper did not empty the file', /export function pairContext/.test(src));
}

// ── 12. …and dynamically: the same vectors, under SW constraints ───────────
// `process`, `Buffer` and `require` are removed and `self` is bound to the
// global before the module is imported, which is the shape an MV3 service
// worker presents. A module that reached for any of them would throw here and
// pass everywhere else — and P3 is the lane that would find out in production.
const swResult = await new Promise((resolve, reject) => {
  const bootstrap = `
    const { parentPort, workerData } = require('node:worker_threads');
    (async () => {
      try {
        const { ctx, pairingId, sessionKeyHex, A, kekHexInputs } = workerData;
        globalThis.self = globalThis;
        delete globalThis.process;
        delete globalThis.Buffer;
        delete globalThis.require;
        globalThis.window = undefined;
        globalThis.document = undefined;
        const m = await import(workerData.url);
        const context = m.fromHex(ctx);
        const keys = await m.trafficKeys({
          pairingId, sessionKey: m.fromHex(sessionKeyHex), context, role: 'phone',
        });
        const sender = { ...keys.send, sessionPrefix: m.fromHex(A.sessionPrefixHex) };
        const ct = await m.seal({
          sender, frameType: A.frameType, kid: A.kid, seq: A.seq, pairEpoch: A.pairEpoch,
          plaintext: new TextEncoder().encode(A.plaintextUtf8),
        });
        const keksOut = [];
        for (const r of kekHexInputs) {
          keksOut.push([r.kind, m.toHex(await m.kek({
            pairingId, sharedSecret: m.fromHex(r.sharedSecretHex), context, recipientKey: r.publicKeySec1Hex,
          }))]);
        }
        let capThrew = false;
        try { m.pairContext({ userId: 'a'.repeat(256), phoneDeviceId: 'b', peerDeviceId: 'c', pairEpoch: 1 }); }
        catch { capThrew = true; }
        parentPort.postMessage({
          ok: true,
          p2c: m.toHex(keys.send.rawBytes),
          c2p: m.toHex(keys.recv.rawBytes),
          ct: m.toHex(ct),
          keks: keksOut,
          capThrew,
        });
      } catch (e) {
        parentPort.postMessage({ ok: false, error: String(e && e.message || e) });
      }
    })();
  `;
  const w = new Worker(bootstrap, {
    eval: true,
    workerData: {
      url: pathToFileURL(KDF_MODULE).href,
      ctx: V.contextBytesHex,
      pairingId: CTX_INPUT.pairingId,
      sessionKeyHex: V.traffic.sessionKeyHex,
      A,
      kekHexInputs: V.kek.recipients.map((r) => ({
        kind: r.kind, publicKeySec1Hex: r.publicKeySec1Hex, sharedSecretHex: V.kek.sharedSecretHex,
      })),
    },
  });
  w.once('message', (m) => { resolve(m); w.terminate(); });
  w.once('error', reject);
});

check('SW context: the module runs with no process/Buffer/require/DOM', swResult.ok, swResult.error);
if (swResult.ok) {
  eq('SW context: k_p2c', swResult.p2c, V.traffic.phoneToComputerKeyHex);
  eq('SW context: k_c2p', swResult.c2p, V.traffic.computerToPhoneKeyHex);
  eq('SW context: vector A ciphertext', swResult.ct, A.ciphertextHex);
  for (const [kind, hex] of swResult.keks) {
    eq(`SW context: ${kind} kek`, hex, V.kek.recipients.find((r) => r.kind === kind).kekHex);
  }
  check('SW context: the u8 cap still throws', swResult.capThrew);
}

